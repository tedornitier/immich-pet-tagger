"""Generate CODEMAP.md: an index of functions/classes with line numbers.

Run from anywhere: python scripts/gen_codemap.py
Covers git-tracked *.py (tests excluded) and app/static/*.js.
"""
import ast
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JS_RE = re.compile(r"^(?:async\s+)?function\s+(\w+)|^const\s+(\w+)\s*=\s*(?:async\s*)?\(.*?\)\s*=>")


def first_line(node):
    doc = ast.get_docstring(node)
    return " ".join(doc.strip().split("\n\n")[0].split()) if doc else ""


def bullet(node, indent=""):
    kind = "async " if isinstance(node, ast.AsyncFunctionDef) else ""
    if isinstance(node, ast.ClassDef):
        sig, kind = node.name, "class "
    else:
        a = node.args
        names = [x.arg for x in a.posonlyargs + a.args + a.kwonlyargs]
        if a.vararg:
            names.append("*" + a.vararg.arg)
        if a.kwarg:
            names.append("**" + a.kwarg.arg)
        sig = f"{node.name}({', '.join(names)})"
    doc = first_line(node)
    return f"{indent}- `{kind}{sig}` L{node.lineno}" + (f": {doc}" if doc else "")


def py_section(src):
    tree = ast.parse(src)
    out, consts = [], []
    if (d := first_line(tree)):
        out.append(d)
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            out.append(bullet(n))
            if isinstance(n, ast.ClassDef):
                for m in n.body:
                    if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        if not m.name.startswith("__") or m.name == "__init__":
                            out.append(bullet(m, "  "))
        elif isinstance(n, ast.Assign):
            consts += [t.id for t in n.targets if isinstance(t, ast.Name) and t.id.isupper()]
    if consts:
        out.append("Constants: " + ", ".join(consts))
    return out


def js_section(src):
    out = []
    for i, line in enumerate(src.splitlines(), 1):
        if m := JS_RE.match(line):
            out.append(f"- `{m.group(1) or m.group(2)}` L{i}")
    return out


def main():
    files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
    lines = ["# Code map", "", "Generated by scripts/gen_codemap.py. Do not edit by hand, rerun the script after code changes."]
    for f in sorted(files):
        is_py = f.endswith(".py") and not f.startswith("tests/")
        is_js = f.startswith("app/static/") and f.endswith(".js")
        if not (is_py or is_js):
            continue
        try:
            src = (ROOT / f).read_text(encoding="utf-8")
            lines += ["", f"## {f}", *(py_section(src) if is_py else js_section(src))]
        except (OSError, SyntaxError, UnicodeDecodeError) as e:
            print(f"warning: skipped {f}: {e}", file=sys.stderr)
    (ROOT / "CODEMAP.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
